// Cada paso tiene su subtítulo (**negrita** sale resaltada), su duración en segundos y sus acciones,
// con el segundo en que empiezan dentro del paso (t) y lo que duran (dur):
//   clic {a}, mover {a}, arrastrar {desde, hasta}, rueda {a, dy}, rango {sel, valor}, opcion {sel, valor},
//   marco {sel}, desplazar {sel}, arriba, js {codigo}, informe (arma el informe con QR y abre la vista previa).
// Un destino {a} es {sel}, {sel, fx, fy} (fracción de la caja), {escena: [fx, fy]} o {x, y}. Un selector
// «filas:<contenedor>|<desde>|<hasta>» toma las filas de resultados de una etiqueta a otra y
// «<iframe> >>> <selector>» busca dentro de la vista previa del informe.
// verificar: expresión que se evalúa al final del paso con --verificar (para revisar las cifras del subtítulo).

